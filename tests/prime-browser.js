(async () => {
  const assert = (condition, label) => { if (!condition) throw Error(label); };
  try {
    const a = window.testAPI;
    const video = document.querySelector('#main-video');
    assert(SubtitlePlayer.getVideo() === video, 'select main player, not hidden preview');
    document.querySelector('.atvwebplayersdk-subtitle-text').textContent = 'シーズン2 第１２話';
    assert(SubtitlePlayer.primeInfo().episodeNumber === 12, 'Japanese episode, not season');
    document.querySelector('.atvwebplayersdk-subtitle-text').textContent = 'S2 E4 — Test';
    assert(SubtitlePlayer.primeInfo().episodeNumber === 4, 'English episode');
    const playerTitle = document.querySelector('.atvwebplayersdk-title-text');
    playerTitle.textContent = '';
    const genericTitle = document.createElement('div');
    genericTitle.dataset.testid = 'title';
    genericTitle.textContent = '映画、TV番組、スポーツ番組、ライブTVを観る';
    document.body.appendChild(genericTitle);
    document.title = '地雷グリコを観る | Prime Video';
    assert(SubtitlePlayer.primeInfo().workTitle === '地雷グリコ', 'strip Japanese Prime watch-title suffix');
    document.title = 'Amazon.co.jp: STEINS;GATE';
    assert(SubtitlePlayer.primeInfo().workTitle === 'STEINS;GATE', 'strip Amazon.co.jp title prefix');
    document.title = '';
    playerTitle.textContent = 'Amazon.co.jp: STEINS;GATE';
    assert(SubtitlePlayer.primeInfo().workTitle === 'STEINS;GATE', 'strip prefix from player title too');
    const genericNavigationTitle = '映画、TV番組、スポーツ番組、ライブTVを観る';
    document.title = `${genericNavigationTitle} | Prime Video`;
    playerTitle.textContent = genericNavigationTitle;
    assert(SubtitlePlayer.primeInfo().workTitle === '', 'ignore transient Prime navigation title');
    genericTitle.remove();
    document.title = '';
    playerTitle.textContent = 'Test Drama';
    Object.defineProperty(video, 'currentTime', { value: 20, writable: true });
    Object.defineProperty(video, 'duration', { value: 100 });
    a.ensureUI();
    // Model host-page CSS loaded after the extension, including Chrome's text fill.
    const hostStyle = document.createElement('style');
    hostStyle.textContent = `input, input:focus { color: transparent !important; -webkit-text-fill-color: transparent !important; opacity: 0.2; background: white; }`;
    document.head.appendChild(hostStyle);
    document.querySelector('#danime-sub-panel').classList.add('open');
    const panel = document.querySelector('#danime-sub-panel');
    const bounds = panel.getBoundingClientRect();
    assert(bounds.left === 18 && bounds.right <= innerWidth - 80, 'Prime panel leaves right controls accessible');
    assert(bounds.bottom <= innerHeight - 96, 'Prime panel leaves bottom controls accessible');
    assert(getComputedStyle(document.querySelector('#danime-sub-fab')).left === '18px', 'Prime button is on left');
    const search = document.querySelector('#dsub-search-title');
    search.value = '仮面ライダー Test';
    search.focus();
    for (const input of document.querySelectorAll('#danime-sub-panel .dsub-input')) {
      const style = getComputedStyle(input);
      assert(style.color === 'rgb(255, 255, 255)', 'input text resists host color');
      assert(style.webkitTextFillColor === 'rgb(255, 255, 255)', 'input text resists host text fill');
      assert(style.opacity === '1', 'input remains opaque');
    }
    search.blur();
    assert(getComputedStyle(search).webkitTextFillColor === 'rgb(255, 255, 255)', 'blurred text stays visible');
    hostStyle.remove();
    await a.detectWorkInfo();
    const titleInput = document.querySelector('#dsub-search-title');
    titleInput.value = 'Visible title';
    const titleStyle = getComputedStyle(titleInput);
    assert(titleStyle.color === 'rgb(255, 255, 255)', 'input value color survives host CSS');
    assert(titleStyle.webkitTextFillColor === 'rgb(255, 255, 255)', 'input text fill survives host CSS');
    assert(titleStyle.opacity === '1', 'input opacity survives host CSS');
    assert(a.state.workInfo.episodeNumber === 4, 'Prime metadata used');
    assert(document.querySelector('#dsub-search-kind').value === 'drama', 'Prime defaults to drama');
    const kindSelect = document.querySelector('#dsub-search-kind');
    kindSelect.value = 'anime';
    kindSelect.dispatchEvent(new Event('change'));
    assert(a.state.settings.workKinds['Test Drama'] === 'anime', 'remember manual kind by work title');
    a.setCues([{start:10,end:12,text:'First'},{start:20,end:22,text:'Second'}], 'test');
    a.toggleLyrics(true);
    document.querySelector('[data-cue="0"]').click();
    assert(a.state.offsetSec === 10 && video.currentTime === 20, 'sync without seeking');
    a.toggleLyrics(true);
    document.querySelector('#danime-sub-lyrics select').value = 'seek';
    document.querySelector('[data-cue="1"]').click();
    assert(video.currentTime === 30, 'seek includes offset');
    video.currentTime = 90;
    a.renderCurrentSubtitle();
    assert(document.querySelector('.danime-sub-box').textContent === '', 'no gap placeholder');
    document.querySelector('.atvwebplayersdk-title-text').textContent = 'Wrong Preview Drama';
    await a.detectWorkInfo();
    assert(a.state.cues.length === 2, 'transient Prime title drift preserves loaded subtitles');
    assert(a.state.workInfo.workTitle === 'Test Drama', 'stable playback keeps its detected title');
    document.querySelector('.atvwebplayersdk-subtitle-text').textContent = 'S2 E5';
    await a.detectWorkInfo();
    assert(!a.state.cues.length && a.state.offsetSec === 0, 'episode transition resets subtitles');
    assert(document.querySelector('#dsub-search-kind').value === 'anime', 'manual kind overrides later detection');
    const calls = [];
    window.fetch = async (url) => {
      calls.push(String(url));
      return {ok:true, json:async()=>[{id:1,name:'Drama'}]};
    };
    const result = await jimakuSearch('Drama', 'test-key', 'drama');
    assert(result.entries.length === 1 && calls.length === 1 && calls[0].includes('anime=false'), 'drama search skips AniList');
    document.querySelector('#result').textContent = 'PASS: input visibility, Prime player, metadata, sync, seek, gaps, episode reset, drama search';
  } catch (error) { document.querySelector('#result').textContent = 'FAIL: ' + error.stack; }
})();
